#!/usr/bin/env python3
"""Regenerate Voce/Resources/THIRD_PARTY_LICENSES.md, the full license texts of code bundled in Sotto.

Reads the Swift package checkouts that scripts/build.sh leaves in .build/deps and fetches a few texts
that the packages do not ship, each from a pinned tag or commit. Run it after changing dependencies,
then commit the result. The app bundles the file in its Resources folder.
"""
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHECKOUTS = ROOT / ".build/deps/SourcePackages/checkouts"
OUTPUT = ROOT / "Voce/Resources/THIRD_PARTY_LICENSES.md"

# (title, where it is used, license file inside the checkout)
PACKAGES = [
    ("FluidAudio", "Parakeet and Nemotron speech recognition", "FluidAudio/LICENSE"),
    ("FluidAudio third-party notice: NeMo text processing", "bundled by FluidAudio", "FluidAudio/ThirdPartyLicenses/NemoTextProcessing-LICENSE.md"),
    ("FluidAudio third-party notice: fastcluster", "bundled by FluidAudio", "FluidAudio/ThirdPartyLicenses/fastcluster-LICENSE.md"),
    ("FluidAudio third-party notice: VBx", "bundled by FluidAudio", "FluidAudio/ThirdPartyLicenses/vbx-LICENSE.md"),
    ("FluidAudio third-party notice: Japanese G2P", "bundled by FluidAudio", "FluidAudio/ThirdPartyLicenses/JapaneseG2P-LICENSE.md"),
    ("FluidAudio third-party notice: Kokoro Spanish and French G2P", "bundled by FluidAudio", "FluidAudio/ThirdPartyLicenses/KokoroAneSpanishFrenchG2P-LICENSE.md"),
    ("Transcribe-cpp-swift", "Cohere Transcribe and SenseVoice", "Transcribe-cpp-swift/LICENSE"),
    ("Transcribe-cpp-swift third-party notices: ggml and miniz", "linked into TranscribeCpp.xcframework", "Transcribe-cpp-swift/THIRD-PARTY-LICENSES.md"),
    ("LLMkit", "Ollama client", "LLMkit/LICENSE"),
    ("SelectedTextKit", "reading the selected text", "SelectedTextKit/LICENSE"),
    ("AXSwift", "used by SelectedTextKit", "AXSwift/LICENSE"),
    ("KeySender", "used by SelectedTextKit", "KeySender/LICENSE"),
    ("swift-markdown-ui (MarkdownUI)", "showing Markdown", "swift-markdown-ui/LICENSE"),
    ("NetworkImage", "used by MarkdownUI", "NetworkImage/LICENSE"),
    ("swift-cmark", "used by MarkdownUI", "swift-cmark/COPYING"),
    ("swift-atomics", "thread-safe counters", "swift-atomics/LICENSE.txt"),
]

# (title, where it is used, pinned URL)
REMOTE = [
    ("mediaremote-adapter (ungive)", "pausing media while recording. Sotto uses ejbills/mediaremote-adapter, a Swift wrapper "
     "that ships no license file and is based on ungive's BSD 3-Clause project; ungive's license follows",
     "https://raw.githubusercontent.com/ungive/mediaremote-adapter/797729d/LICENSE"),
    ("whisper.cpp", "Whisper speech recognition, the prebuilt v1.8.2 XCFramework",
     "https://raw.githubusercontent.com/ggml-org/whisper.cpp/v1.8.2/LICENSE"),
    ("Silero VAD", "Voce/Resources/models/ggml-silero-v5.1.2.bin, voice detection for Whisper",
     "https://raw.githubusercontent.com/snakers4/silero-vad/v5.1.2/LICENSE"),
]


def section(title: str, usage: str, text: str) -> str:
    # Four backticks, because some notices contain three-backtick blocks themselves.
    return f"## {title}\n\nUsed for: {usage}.\n\n````\n{text.strip()}\n````\n"


def main() -> None:
    if not CHECKOUTS.is_dir():
        sys.exit("Run scripts/build.sh first so the package checkouts exist in .build/deps.")
    parts = [
        "# Third-party licenses\n\n"
        "Sotto is GPL v3 (see LICENSE). It bundles the code below under its own licenses. "
        "Generated by scripts/third-party-licenses.py.\n"
    ]
    for title, usage, relative in PACKAGES:
        parts.append(section(title, usage, (CHECKOUTS / relative).read_text()))
    for title, usage, url in REMOTE:
        with urllib.request.urlopen(url, timeout=30) as response:
            parts.append(section(title, usage, response.read().decode()))
    OUTPUT.write_text("\n".join(parts))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
